type CommonsImage = (typeof commonsImages)[keyof typeof commonsImages];
type CommonsId = keyof typeof commonsImages;

/** Commons에서 받은 이미지 정보에 대체 텍스트를 붙입니다. (scripts/resolve-commons.mjs) */
function image(id: CommonsId, alt: string): ArchiveImage {
  const { src, width, height, license, licenseUrl, artist, sourceUrl }: CommonsImage =
    commonsImages[id];
  return { src, width, height, alt, credit: { artist, license, licenseUrl, sourceUrl } };
}

