/** /images/exhibits/{id}.jpg 주소가 원본을 그대로 보내야 하는 그림인지 */
export function skipsOptimization(src: string): boolean {
  const match = /^\/images\/exhibits\/([a-z0-9-]+)\.jpg$/.exec(src);
  return match !== null && ORIGINAL_IDS.has(match[1]);
}

/**
 * 비밀 전시실 캔버스 타일처럼 작게 보이는 자리에 쓸 주소.
 * 최적화를 건너뛰는 그림은 큰 원본 대신 미리 줄여 둔 작은 그림(`public/images/exhibits-thumb/`, 긴 변 480px)을 보냅니다.
 * 원본을 그대로 보내면 첫 화면 LCP가 4초대로 늘어 Lighthouse 성능이 0.8 아래로 떨어집니다.
 */
export function smallSrc(src: string): string {
  return skipsOptimization(src) ? src.replace("/images/exhibits/", "/images/exhibits-thumb/") : src;
}
